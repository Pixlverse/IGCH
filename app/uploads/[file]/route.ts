import { readFile } from 'node:fs/promises'
import { extname, join } from 'node:path'

import { LOCAL_UPLOAD_DIR } from '@/lib/admin/storage'

const TYPES: Record<string, string> = {
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.png': 'image/png',
  '.webp': 'image/webp',
  '.avif': 'image/avif',
  '.pdf': 'application/pdf',
}

/** Serves admin uploads stored on disk when Cloudinary is not configured (local only). */
export async function GET(_request: Request, { params }: { params: Promise<{ file: string }> }) {
  const { file } = await params
  const type = TYPES[extname(file).toLowerCase()]
  // names are generated by lib/admin/storage.ts; reject anything else (no path traversal)
  if (process.env.VERCEL || !type || !/^[a-z0-9-]+\.[a-z0-9]+$/.test(file))
    return new Response('Not found', { status: 404 })
  try {
    const body = await readFile(join(LOCAL_UPLOAD_DIR, file))
    return new Response(body, {
      headers: { 'Content-Type': type, 'Cache-Control': 'public, max-age=31536000, immutable' },
    })
  } catch {
    return new Response('Not found', { status: 404 })
  }
}
